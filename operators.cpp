// Using operators like addition, subtraction, multiplication, division, modulus(remainder)

//(the operations are done for integers.)

#include<iostream>
using namespace std;
int main(){
int a,b;

cout<<"Enter the first number: ";
cin>>a;

cout<<"Enter the second number: ";
cin>>b;

cout <<"Addition: "<< a+b <<endl;
cout <<"Subtraction: "<< a-b <<endl;
cout <<"Multiplication: "<< a*b <<endl;
cout <<"Division"<< a/b <<endl;
cout <<"Remainder: "<< a%b <<endl;

return 0;
}

